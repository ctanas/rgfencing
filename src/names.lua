local function words(s)
  local t = {}
  for w in s:gmatch("%S+") do t[#t + 1] = w end
  return t
end

N.CODES = {}
local LISTS = {}
for code, d in pairs(DATA) do
  N.CODES[#N.CODES + 1] = code
  LISTS[code] = { m = words(d[1]), f = words(d[2]), s = words(d[3]) }
end
table.sort(N.CODES)

-- A random fencer name. gender: "m", "f" or nil (either).
-- `used` (optional) is a set of surnames to avoid.
function N.random(gender, rng, used)
  local function rand(a, b)
    if rng then return rng:random(a, b) end
    return love.math.random(a, b)
  end
  for _ = 1, 30 do
    local code = N.CODES[rand(1, #N.CODES)]
    local L = LISTS[code]
    local g = gender or (rand(1, 2) == 1 and "m" or "f")
    local first = L[g][rand(1, #L[g])]
    local last = L.s[rand(1, #L.s)]
    if not used or not used[last] then
      if used then used[last] = true end
      return { first = first, last = last, nation = code }
    end
  end
  return { first = "ALEX", last = "DOE", nation = "USA" }
end

return N
