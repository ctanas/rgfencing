-- Accented capitals, built from the base letter and an accent (two rows
-- above the capital) or a mark below (two rows under the baseline).
local ACCENT5 = {
  grave = ".#.../..#..", acute = "...#./..#..", circ = "..#../.#.#.", uml = "...../.#.#.",
  ring = ".###./.#.#.", breve = "#...#/.###.", caron = ".#.#./..#..", dacute = "..#.#/.#.#.",
