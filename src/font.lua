for ch, g in pairs(GEN) do
  local base = G[g[1]]
  local w = #base:match("^[^/]*")
  if g[2] then
    local acc = (w == 3 and ACCENT3 or ACCENT5)[g[2]]
    G[ch] = "!" .. acc .. "/" .. base
  else
    G[ch] = base .. "/" .. BELOW[g[3]]
  end
end
G["Ø"] = ".###./#..##/#..##/#.#.#/##..#/##..#/.###."
G["Ł"] = "#..../#..../#.#../##.../#..../#..../#####"
G["ß"] = ".##../#..#./#..#./###../#..#./#..#./#.##."

local ORDER = {}
for ch in pairs(G) do ORDER[#ORDER + 1] = ch end
table.sort(ORDER)

-- Every character the font can draw (the name keyboard uses this).
local font = { HAS = {} }
for ch in pairs(G) do font.HAS[ch] = true end

local H = 11

local function rows(def)
  local start = 2
  if def:sub(1, 1) == "!" then
    start = 0
    def = def:sub(2)
  end
  local r = {}
  for row in (def .. "/"):gmatch("([^/]*)/") do r[#r + 1] = row end
  return r, start
end

function font.build()
  -- total width: a separator column before each glyph and at the end
  local total = 1
  local parsed = {}
  for i, ch in ipairs(ORDER) do
    local r, start = rows(G[ch])
    local w = #r[1]
    for _, row in ipairs(r) do
      assert(#row == w, "font: ragged glyph '" .. ch .. "'")
    end
    parsed[i] = { r = r, start = start, w = w }
    total = total + w + 1
  end
  local img = love.image.newImageData(total, H)
  local x = 0
  local function sep(col)
    for y = 0, H - 1 do img:setPixel(col, y, 1, 0, 1, 1) end
  end
  sep(0)
  x = 1
  for i = 1, #ORDER do
    local p = parsed[i]
    for ry, row in ipairs(p.r) do
      local y = p.start + ry - 1
      for cx = 1, p.w do
        if row:sub(cx, cx) == "#" and y < H then img:setPixel(x + cx - 1, y, 1, 1, 1, 1) end
      end
    end
    x = x + p.w
    sep(x)
    x = x + 1
  end
  local f = love.graphics.newImageFont(img, table.concat(ORDER), 1)
  f:setFilter("nearest", "nearest")
  return f
end

-- Offset from the drawing y to the top of the capitals.
font.CAP = 2
font.H = H
font.LINE = 10

return font
